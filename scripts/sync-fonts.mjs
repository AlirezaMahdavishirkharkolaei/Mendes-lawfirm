// Copies the self-hosted fonts from @fontsource into public/fonts and
// writes src/styles/fonts.css with absolute /fonts/… URLs.
//
// Why: importing @fontsource CSS directly leaves relative ./files/… URLs
// that the production build doesn't emit, so fonts silently fell back to
// system fonts on the live site. Run after upgrading a font package:
//   node scripts/sync-fonts.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCES = [
  "@fontsource-variable/cormorant-garamond/wght.css",
  "@fontsource-variable/cormorant-garamond/wght-italic.css",
  "@fontsource-variable/inter/wght.css",
  "@fontsource-variable/vazirmatn/wght.css",
  "@fontsource/ibm-plex-mono/400.css",
];
const SKIP = /vietnamese|greek/;

mkdirSync(join(root, "public/fonts"), { recursive: true });
let css = "/* Generated by scripts/sync-fonts.mjs — do not edit by hand. */\n";
for (const source of SOURCES) {
  const file = join(root, "node_modules", source);
  const blocks = readFileSync(file, "utf8").split(/(?=\/\* )/);
  for (const block of blocks) {
    if (!block.includes("@font-face") || SKIP.test(block)) continue;
    css += block.replace(/url\(\.\/files\/([^)]+)\)/g, (_, name) => {
      copyFileSync(join(dirname(file), "files", name), join(root, "public/fonts", name));
      return `url(/fonts/${name})`;
    });
  }
}
writeFileSync(join(root, "src/styles/fonts.css"), css);
console.log("fonts synced");
